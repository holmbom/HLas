#pragma once
// GYLLENE VEKTORER FÖR PUNKTFORMAT 0-5 — genererade av referensen, inte av oss.
//
// GENERERAD FIL. Ändra den inte för hand.
//
// Samma ursprung och samma skäl som [golden_ref.h](golden_ref.h), men
// ett annat filupplägg: format 0-5 komprimeras med compressor 2, alltså UTAN
// lagerindelning. Chunken är seed-posten rått följd av EN aritmetisk ström där
// varje punkts items kodas efter varandra i den ordning de står i LAZ-VLR:n.
// Det finns därför inga lagerlängder att mäta — bara strömmens storlek, som
// står i kommentaren över varje fall.
//
// GPS och RGB är KONSTANTA i grundposten, av samma skäl som i format
// 6-generatorn: fallen som prövar Point10 ska gå att koda även av en kodare som
// ännu inte har GPSTime11 eller RGB12. De fall som heter p10_gps*, p10_rgb* och
// p10_full är just de som rör dem.
//
//   p10_basic      vanliga punkter i format 0
//   p10_returns    ALLA 64 rutor i kReturnMap och kReturnLevel, inklusive de
//                  "omöjliga" kombinationerna tabellerna finns för: retur 0,
//                  retur större än antalet returer, och antal returer 0. En
//                  felaktig ruta syns bara i det här fallet. Fallet har 65
//                  punkter och inte 64: seed-posten går FÖRBI tabellerna, så
//                  kombinationen 0 av 0 nås först av punkt 65. Att täckningen
//                  verkligen är fullständig kontrolleras av testet, inte av
//                  den här kommentaren
//   p10_flags      scanriktning och edge-of-flight växlar. Scanriktningen väljer
//                  VILKEN av de två scanvinkelmodellerna som används, så vinkeln
//                  varieras samtidigt för att båda ska nås
//   p10_constant   allt utom seed-posten identiskt: masken blir noll för varje
//                  punkt. dX och dY blir noll, men den FÖRSTA Z-korrektorn blir
//                  seed-postens hela Z — höjdhistoriken börjar på noll och
//                  seed-punkten fyller den inte. Fallet prövar alltså just det
//   p10_intensity  DET AVGÖRANDE FALLET. Intensiteten jämförs inte med
//                  föregående punkt utan med den senaste intensiteten för samma
//                  retur-klass m. Punkterna växlar mellan två m-klasser med var
//                  sin fasta intensitet, så masken ska ha intensitetsbiten
//                  NOLLSTÄLLD trots att intensiteten skiljer sig från punkten
//                  närmast före. En kodare som jämför med föregående punkt
//                  divergerar på punkt fyra: seed lämnar historiken på noll,
//                  punkt två och tre är ändrade för båda varianterna, och först
//                  punkt fyra skiljer dem åt
//   p10_extremes   INT32_MIN/MAX i koordinaterna: differenserna wrappar och
//                  korrektorn kräver k = 32
//   p10_attrs      klass, user data, point source och scanvinkel spridda över
//                  hela sina värdeområden. Klassen är HELA byten i format 0-5,
//                  flaggbitarna inräknade
//
// Fallen nedan rör GPSTime11 och RGB12, alltså items som ligger EFTER Point10 i
// samma ström. Ett utelämnat item tar därför inte bara fel byte — det flyttar
// alla följande.
//
//   p10_gps        punktformat 1: tiden växlar mellan mikrosekunder och hopp på
//                  1e9, vilket tvingar fram sekvensbyten och fulla värden
//   p10_gps_repeat blandar oförändrad tid, små steg och sekvensbyten, så att
//                  grenen för nolldifferens nås tillsammans med multi-koderna
//   p10_gps_multi  steg som är 1, 3, 15, 600, -3, -20 och en tiondel gånger
//                  föregående steg. Fallet finns för att de andra GPS-fallen
//                  lämnade tre av IntegerCompressorns nio instanser oanvända:
//                  den för multipel >= 10, och de två ytterlighetsgrenarna.
//                  MED fallet nås alla nio. Det är mätt och inte påstått —
//                  kodaren instrumenterades tillfälligt att skriva ut vilken
//                  instans varje anrop gick till, och utfallet över samtliga
//                  GPS-vektorer blev instans 0:15, 1:83, 2:23, 3:3, 4:6, 5:6,
//                  6:5, 7:8 och 8:11 anrop
//   p10_gps_frames DET FALL SOM PRÖVAR FACKRÄKNARNA. Referensen håller TVÅ:
//                  `last` flyttas av ett sekvensbyte, `next` pekar ut facket som
//                  tas i bruk vid nästa fulla värde. Räknar man fram det nya
//                  facket ur `last` är de lika ända tills ett sekvensbyte skilt
//                  dem åt — och först DÅ hamnar man i fel fack. Fallet gör
//                  precis den följden: bygg fack 0, fullt värde, byt tillbaka,
//                  fullt värde igen, och gå sedan till det fack som höll den
//                  andra tiden. Vår avkodare hade den buggen och fångades av
//                  just det här fallet
//   p10_rgb        punktformat 2: RGB utan GPS, alltså färgen vid byte 20
//   p10_rgb_gray   R == G == B, vilket sätter bit 6 i RGB-masken och gör att
//                  bara rött kodas. Mätt: 282 byte mot p10_rgb:s 414, alltså 68 %
//   p10_full       punktformat 3: Point10, GPSTime11 och RGB12 i samma ström.
//                  Det är las/autzen.laz form
//
// Varje vektor är rundgångstestad genom referensen innan den frystes.

